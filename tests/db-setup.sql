-- Minimal stand-ins for the Supabase pieces the migration relies on,
-- so the schema can be tested on a plain PostgreSQL server (local or CI).
create schema if not exists auth;
create table if not exists auth.users (id uuid primary key default gen_random_uuid());
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
do $$ begin
  if not exists (select from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
  if not exists (select from pg_roles where rolname = 'anon') then create role anon; end if;
end $$;

-- Supabase grants the API roles broad table privileges and relies on RLS to restrict them.
-- Mirror that, so these tests prove RLS (not missing grants) is what blocks access.
grant usage on schema public to anon, authenticated;
grant usage on schema auth to anon, authenticated;
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
